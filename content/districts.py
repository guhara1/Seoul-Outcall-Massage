def _make_district_page(gu_slug):
    d = DISTRICTS[gu_slug]
    zone_slug, zone_name = _zone_of(gu_slug)
    return {
        "path": f"{gu_slug}/",
        "title": d["title"],
        "desc": d["desc"],
        "h1": f"{d['name']} 출장마사지",
        "breadcrumb": [
            ("서울", "/"),
            (zone_name, f"/zone/{zone_slug}/"),
            (d["name"], ""),
        ],
        "body": _district_body(gu_slug, d),
    }


DISTRICT_PAGES = [_make_district_page(slug) for slug in DISTRICT_ORDER]


