def _matched_tips(desc):
    out = []
    for kws, htmltip in TYPE_TIPS:
        if any(k in desc for k in kws):
            out.append(htmltip)
    if len(out) < 2:
        out.append(_GENERIC_TIP)
    # 순서 유지 중복 제거
    return "".join(dict.fromkeys(out))


